import { build } from 'esbuild';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

await build({
  absWorkingDir: root,
  entryPoints: ['src/server/vercelCards.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  outfile: 'api/cards.js',
  legalComments: 'none',
  logLevel: 'info',
  banner: {
    js: '// Generated by scripts/bundle-vercel-api.mjs — do not edit. Source: src/server/vercelCards.ts',
  },
});
